"""Chat guardrails for the AssetMind / Prudentia chat (Saathi intake + post-result chat).

Pure-Python, deterministic checks that run AROUND the LLM, never inside it:

  1. check_input()          gate every user message BEFORE any model sees it
  2. slots_have_evidence()  every slot the model extracted must be backed by the user's own words
  3. reply_is_grounded()    a model-written reply may only use numbers it was given

Design rule (the one that actually protects the app): user text only ever reaches a
locked, schema-limited extractor. It never reaches a model that can write free text.
Refusals are fixed templates written here, never generated by the model.

Adapted from Kavya's chat_guardrails.py with these changes for Saathi:
  * state-aware gate: when the bot is waiting for a slot ("kitne saal?"), a bare
    answer like "3 saal" or "kam" must pass
  * Hinglish + Devanagari vocabulary and Hindi number words ("paanch lakh", "teen saal")
  * several fixed refusal templates instead of one
  * evidence checks for amount / years / risk / classes
"""
from __future__ import annotations

import logging
import re
import unicodedata
from dataclasses import dataclass
from typing import Iterable, Mapping

logger = logging.getLogger(__name__)

MAX_CHARS = 300

INTENTS = ("provide_inputs", "modify_inputs", "ask_result", "ask_app", "out_of_scope")
ALL_CLASSES = ("stocks", "mf", "fd")

