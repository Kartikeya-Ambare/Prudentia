# --------------------------------------------------------------------------- normalise
_INVISIBLE = re.compile(r"[​-‏‪-‮⁠﻿]")
_CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
_DEVANAGARI_DIGITS = str.maketrans("०१२३४५६७८९", "0123456789")

# Hindi number words -> digits. Only converted when followed by a unit word, so the English
# word "do" in "what do I do" is left alone.
_HI_NUM = {
    "ek": 1, "do": 2, "teen": 3, "char": 4, "chaar": 4, "paanch": 5, "panch": 5, "chhe": 6, "chhah": 6,
    "che": 6, "saat": 7, "aath": 8, "nau": 9, "das": 10, "gyarah": 11, "barah": 12, "terah": 13,
    "chaudah": 14, "pandrah": 15, "solah": 16, "satrah": 17, "atharah": 18, "unnis": 19, "bees": 20,
    "pachees": 25, "tees": 30, "chalis": 40, "pachas": 50, "dedh": 1.5, "dhai": 2.5, "sau": 100,
}
_UNIT_WORDS = (
    r"lakhs?|lacs?|crores?|cr|hazaa?r|hajar|saalon|saal|sal|varsh|years?|yrs?|yr|percent|pratishat|prati\s?shat"
)
_HI_WORD_BEFORE_UNIT = re.compile(
    r"\b(" + "|".join(sorted(_HI_NUM, key=len, reverse=True)) + r")\s+(" + _UNIT_WORDS + r")\b", re.I
)


def normalise(text: str) -> str:
    text = unicodedata.normalize("NFKC", text or "")
    text = text.translate(_DEVANAGARI_DIGITS)
    text = _INVISIBLE.sub("", text)
    text = _CONTROL.sub(" ", text)
    return re.sub(r"\s+", " ", text).strip()


_EN_ONES = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
            "eleven": 11, "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16, "seventeen": 17,
            "eighteen": 18, "nineteen": 19}
_EN_TENS = {"twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60, "seventy": 70, "eighty": 80, "ninety": 90}
_EN_UNITS = r"lakhs?|lacs?|crores?|thousand|years?|yrs?|percent|per\s?cent"
_EN_WORD_BEFORE_UNIT = re.compile(
    r"\b(?:(" + "|".join(_EN_TENS) + r")(?:[\s-](" + "|".join(k for k, v in _EN_ONES.items() if v < 10) + r"))?"
    r"|(" + "|".join(sorted(_EN_ONES, key=len, reverse=True)) + r")|(a))"
    r"(\s+and\s+(?:a\s+)?half)?\s+(" + _EN_UNITS + r")\b", re.I
)


def words_to_digits(text: str) -> str:
    """'paanch lakh' -> '5 lakh', 'teen saal' -> '3 saal', 'five lakh' -> '5 lakh', 'twenty five percent' -> '25 percent'."""
    def _hi(m: re.Match) -> str:
        v = _HI_NUM[m.group(1).lower()]
        return f"{v:g} {m.group(2)}"

    def _en(m: re.Match) -> str:
        tens, ones, small, article, half, unit = m.groups()
        if article and not re.match(r"lakhs?|lacs?|crores?|thousand", unit, re.I) \
                and not re.search(r"\b(for|over|next|within|after)\s+$", m.string[:m.start()], re.I):
            return m.group(0)                                   # 'a year' in 'how many days in a year' is not a number; 'for a year' is
        if tens:
            v = _EN_TENS[tens.lower()] + (_EN_ONES[ones.lower()] if ones else 0)
        elif small:
            v = _EN_ONES[small.lower()]
        else:
            v = 1
        return f"{v + (0.5 if half else 0):g} {unit}"
    return _EN_WORD_BEFORE_UNIT.sub(_en, _HI_WORD_BEFORE_UNIT.sub(_hi, text))


# --------------------------------------------------------------------------- numbers
_NUM = re.compile(
    r"(\d+(?:,\d{2,3})*(?:\.\d+)?)\s*(k|lakhs?|lacs?|l|crores?|cr|hazaa?r|hajar|thousand)?(?![a-z])", re.I
)
_MULT = {
    "k": 1e3, "thousand": 1e3, "hazaar": 1e3, "hazar": 1e3, "hajar": 1e3,
    "lakh": 1e5, "lakhs": 1e5, "lac": 1e5, "lacs": 1e5, "l": 1e5,
    "crore": 1e7, "crores": 1e7, "cr": 1e7,
}


def numbers_in(text: str) -> set[float]:
    """Every number the text could mean, raw and unit-expanded ('5 lakh' -> {5, 500000})."""
    text = words_to_digits(normalise(text))
    out: set[float] = set()
    for raw, unit in _NUM.findall(text):
        val = float(raw.replace(",", ""))
        out.add(round(val, 2))
        if unit:
            out.add(round(val * _MULT[unit.lower()], 2))
    return out


_YEARS = re.compile(r"(\d+(?:\.\d+)?)\s*(?:saalon|saal|sal|varsh|years?|yrs?|yr|y|वर्ष|साल)(?![a-z])", re.I)


def years_in(text: str) -> set[float]:
    text = words_to_digits(normalise(text))
    return {round(float(m), 2) for m in _YEARS.findall(text)}


# --------------------------------------------------------------------------- risk + classes
_RISK_LOW_NEG = re.compile(
    r"(zyada|jyada|jyaada|high|bahut|too\s+much|much)\s+risk\s+(nahi|nhi|na|not)"
    r"|risk\s+(zyada|jyada|high|bahut)\s+(nahi|nhi|na)"
    r"|(not|no|don'?t\s+want|dont\s+want)\s+(much\s+|high\s+|too\s+much\s+)?risk"
    r"|(zero|no)\s+risk|risk\s+(nahi|nhi)\s+(lena|chahiye|leni)"
    r"|(can'?t|cannot|can\s+not|unable\s+to|won'?t|couldn'?t|shouldn'?t)\s+(take|handle|afford|bear|tolerate|stomach|accept)\s+(much\s+|any\s+|high\s+|too\s+much\s+)?risk"
    r"|risk[- ]averse|\bplay\s+it\s+safe\b|(low|no)\s+(risk\s+)?tolerance|(scared|afraid)\s+of\s+(losing|risk)|can'?t\s+(afford\s+to\s+)?lose",
    re.I,
)
_RISK_LOW = re.compile(r"\b(kam|kum|low|safe|safest|conservative|thoda\s+risk|less\s+risk|minimal)\b", re.I)
_RISK_MOD = re.compile(r"\b(medium|moderate|balanced|normal|beech|madhyam)\b", re.I)
_RISK_HIGH = re.compile(r"\b(zyada|jyada|jyaada|high|aggressive|bahut\s+risk|risky|max(imum)?)\b", re.I)
_RISK_CONTEXT = re.compile(r"\brisk\b|\bjokhim\b|जोखिम", re.I)


def risk_from_words(text: str) -> str | None:
    """Map plain words to low | moderate | high, or None if the user did not say. Negation first."""
    t = normalise(text)
    if _RISK_LOW_NEG.search(t):
        return "low"
    if _RISK_CONTEXT.search(t) or re.fullmatch(r"(?i)(kam|low|medium|moderate|high|zyada|safe|aggressive)", t):
        if _RISK_MOD.search(t):
            return "moderate"
        if _RISK_HIGH.search(t):
            return "high"
        if _RISK_LOW.search(t):
            return "low"
    return None


_CLASS_SYNONYMS = {
    "stocks": re.compile(r"\b(stocks?|shares?|equit(?:y|ies)|share\s+market)\b|शेयर", re.I),
    "mf": re.compile(r"\b(mutual\s+funds?|mfs?|funds?)\b|म्यूचुअल", re.I),
    "fd": re.compile(r"\b(fds?|fixed\s+deposits?|deposits?|banks?)\b|एफडी", re.I),
}


def classes_in(text: str) -> set[str]:
    t = normalise(text)
    return {k for k, rx in _CLASS_SYNONYMS.items() if rx.search(t)}


