@dataclass
class GuardResult:
    allowed: bool
    category: str   # ok | ok_slot | empty | too_long | unsupported_language | injection | suspicious
    #                 | sip_unsupported | no_tips | unsupported_topic | off_topic
    message: str | None
    cleaned: str


def looks_like_slot_answer(cleaned: str, awaiting: Iterable[str]) -> bool:
    """True if `cleaned` plausibly answers a question the bot just asked."""
    aw = set(awaiting or ())
    if not aw:
        return False
    if _DONT_KNOW.search(cleaned):
        return True
    t = words_to_digits(cleaned)
    if "confirm" in aw and _CONFIRM.match(cleaned.strip()):
        return True
    if "risk_scenario" in aw and _SCENARIO.search(cleaned.strip()):
        return True
    if "risk" in aw and (risk_from_words(cleaned) is not None
                         or re.fullmatch(r"\d{1,3}(?:\.\d+)?\s*(?:%|percent)", cleaned.strip(), re.I)):
        return True
    if "years" in aw and (years_in(t) or re.fullmatch(r"\s*\d{1,2}(\.\d)?\s*", t)):
        return True
    if "amount" in aw and (_MONEY_CUE.search(t) or any(n >= 1000 for n in numbers_in(t))):
        return True
    if "classes" in aw and (classes_in(cleaned) or re.search(r"\b(sab|all|teeno|everything|anything|koi\s+bhi)\b", cleaned, re.I)):
        return True
    return False


def check_input(
    message: str,
    awaiting: Iterable[str] | None = None,
    extra_terms: frozenset[str] = frozenset(),
) -> GuardResult:
    """Gate a message before any model sees it.

    awaiting: slot names the bot is currently asking for, e.g. {"years"}, {"risk_scenario"},
    {"confirm"}. Pass it from the chat session state so short answers are not blocked.
    extra_terms: lower-cased fund names so 'explain Parag Parikh Flexi Cap' passes.
    """
    cleaned = normalise(message)
    if not cleaned:
        return _res(False, "empty", cleaned)
    if len(cleaned) > MAX_CHARS:
        return _res(False, "too_long", cleaned)
    if _NON_LATIN.search(cleaned):
        return _res(False, "unsupported_language", cleaned)
    scan = words_to_digits(cleaned)
    if _INJECTION.search(scan):
        return _res(False, "injection", cleaned)
    if _SUSPICIOUS.search(scan):
        return _res(False, "suspicious", cleaned)
    # category refusals run BEFORE the domain gate: "konsa stock kharidu" contains 'stock'
    if _SIP.search(scan):
        return _res(False, "sip_unsupported", cleaned)
    if _ADVICE.search(scan):
        return _res(False, "no_tips", cleaned)
    if _UNSUPPORTED.search(scan):
        return _res(False, "unsupported_topic", cleaned)
    if looks_like_slot_answer(cleaned, awaiting or ()):
        return _res(True, "ok_slot", cleaned)
    lowered = cleaned.lower()
    if _DOMAIN.search(scan) or _MONEY_CUE.search(scan) or any(t in lowered for t in extra_terms):
        return _res(True, "ok", cleaned)
    return _res(False, "off_topic", cleaned)


def _res(allowed: bool, category: str, cleaned: str) -> GuardResult:
    msg = None if allowed else REFUSALS[category]
    if not allowed:
        logger.info("chat_blocked category=%s text=%.80r", category, cleaned)
    return GuardResult(allowed, category, msg, cleaned)


# --------------------------------------------------------------------------- evidence
def slots_have_evidence(
    slots: Mapping[str, object], message: str, awaiting: Iterable[str] | None = None
) -> tuple[bool, list[str]]:
    """Check each slot the model filled against the user's own words.

    Returns (ok, bad_fields). A bad field means the model invented it: ask the user
    ("clarify") instead of acting. Slots left as None are fine (they become follow-up questions).
    awaiting: slots the bot just asked for; a bare number then counts as an answer.
    """
    aw = set(awaiting or ())
    text = words_to_digits(normalise(message))
    bad: list[str] = []

    amount = slots.get("amount")
    if amount is not None and round(float(amount), 2) not in numbers_in(text):
        bad.append("amount")

    years = slots.get("years")
    if years is not None:
        ok = round(float(years), 2) in years_in(text)
        if not ok and "years" in aw:
            ok = round(float(years), 2) in numbers_in(text)
        if not ok:
            bad.append("years")

    risk = slots.get("risk")
    if risk is not None and "risk_scenario" not in aw:
        if isinstance(risk, str):
            if risk_from_words(text) != risk:
                bad.append("risk")
        else:  # numeric 0-100 score must be quoted by the user
            if round(float(risk), 2) not in numbers_in(text):
                bad.append("risk")

    classes = slots.get("classes")
    if classes:
        mentioned = classes_in(text)
        extracted = set(classes)
        defaulted = extracted == set(ALL_CLASSES) and not mentioned
        if not defaulted and not extracted <= mentioned:
            bad.append("classes")
    return (not bad, bad)


# --------------------------------------------------------------------------- reply grounding
_ADVICE_REPLY = re.compile(
    r"\byou\s+should\s+(buy|sell|invest)|\bguaranteed?\b|\brisk[- ]free\b|\bsure[- ]?shot\b|"
    r"\bwill\s+definitely\b|\bbest\s+stock\b|\bpakka\b", re.I
)


def _strict_values(text: str) -> set[float]:
    """Like numbers_in, but '5 lakh' counts only as 500000 (not also as 5)."""
    text = words_to_digits(normalise(text))
    out: set[float] = set()
    for raw, unit in _NUM.findall(text):
        val = float(raw.replace(",", ""))
        out.add(round(val * _MULT[unit.lower()], 2) if unit else round(val, 2))
    return out


def reply_is_grounded(reply: str, source_text: str, max_chars: int = 1200) -> bool:
    """A model-written reply may only use numbers that appear in `source_text`."""
    if not reply or len(reply) > max_chars or _ADVICE_REPLY.search(reply):
        return False
    return _strict_values(reply) <= numbers_in(source_text)
